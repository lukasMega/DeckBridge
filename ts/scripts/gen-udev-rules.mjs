#!/usr/bin/env node
// Generates scripts/packaging/linux/99-deckbridge.rules from DEVICE_MODELS
// (--check: fail if stale, write nothing).

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from './registry-loader.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(REPO, 'scripts/packaging/linux/99-deckbridge.rules');
const OUT_REL = 'scripts/packaging/linux/99-deckbridge.rules';

const HEADER = `# udev rule for DeckBridge — grants non-root access to supported stream deck
# devices via /dev/hidraw*.
#
# GENERATED by ts/scripts/gen-udev-rules.mjs from DEVICE_MODELS — do not edit.
# Run 'mise run devices-generate' after changing a VID/PID in ts/src/devices/.
#
# Two grants per device, so it works both with and without systemd-logind:
#   - TAG+="uaccess"            — logind ACL grants access to the active
#                                 seat's session user (systemd-based systems,
#                                 including most Raspberry Pi OS / DietPi).
#   - MODE="0660", GROUP="plugdev" — fallback for minimal/non-logind setups
#                                 (some DietPi images); add the deckbridge
#                                 user to the \`plugdev\` group (install.sh
#                                 does this).
`;

const hex4 = (n) => n.toString(16).padStart(4, '0');
const rule = (vid, pid) =>
  `KERNEL=="hidraw*", ATTRS{idVendor}=="${hex4(vid)}", ATTRS{idProduct}=="${hex4(pid)}", TAG+="uaccess", MODE="0660", GROUP="plugdev"`;

/** Emit only DEVICE_MODELS: profiles and the browser deck are never USB devices.
 *  Duplicate VID:PID pairs never get here: loadRegistry's validateCatalog rejects them. */
function render(models) {
  const pairs = [];
  const blocks = [];
  for (const m of models) {
    const lines = [`# ${m.name} (vendor 0x${hex4(m.usbVendorId)})`];
    for (const pid of new Set(m.usbProductIds)) {
      pairs.push(`${hex4(m.usbVendorId)}:${hex4(pid)}`);
      lines.push(rule(m.usbVendorId, pid));
    }
    blocks.push(lines.join('\n'));
  }
  return { text: `${HEADER}\n${blocks.join('\n\n')}\n`, pairs };
}

const pairsOf = (text) =>
  [...text.matchAll(/idVendor\}=="([0-9a-f]{4})".*idProduct\}=="([0-9a-f]{4})"/g)].map(
    (x) => `${x[1]}:${x[2]}`,
  );

async function main() {
  const check = process.argv.includes('--check');
  const { DEVICE_MODELS } = await loadRegistry();
  const { text, pairs } = render(DEVICE_MODELS);

  if (!check) {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT_REL} (${pairs.length} rules)`);
    return;
  }
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (have === text) {
    console.log(`udev rules up to date (${pairs.length} rules)`);
    return;
  }
  const haveSet = new Set(pairsOf(have));
  const wantSet = new Set(pairs);
  const missing = pairs.filter((p) => !haveSet.has(p));
  const extra = [...haveSet].filter((p) => !wantSet.has(p));
  console.error(`stale: ${OUT_REL}`);
  if (missing.length) console.error(`missing VID:PID: ${missing.join(', ')}`);
  if (extra.length) console.error(`extra VID:PID: ${extra.join(', ')}`);
  console.error("\nThe udev rules no longer match DEVICE_MODELS. Run 'mise run devices-generate'.");
  process.exitCode = 1;
}

await main();
