// AUTO-RUN: node ts/scripts/gen-deck-icons.mjs (from deckbridge/)
// Regenerates ts/src/assets/deck-icons.ts — the browser deck's home-screen PNGs. Commit the output.
// Recompressed losslessly with oxipng when it is on PATH (`brew install oxipng`, ~60% smaller);
// without it the canvas PNGs are used as is, so regenerating works anywhere.
import { createCanvas } from '@napi-rs/canvas';
import { spawnSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const __dir = dirname(fileURLToPath(import.meta.url));
const assetDir = join(__dir, '../src/assets');

function roundRect(ctx, x, y, w, h, r) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}

// iOS rounds the corners itself, so the icon is a full-bleed black square with a 3x2 key grid.
function makeIcon(size) {
  const c = createCanvas(size, size);
  const ctx = c.getContext('2d');
  ctx.fillStyle = '#000000';
  ctx.fillRect(0, 0, size, size);
  const cols = 3;
  const rows = 2;
  const margin = size * 0.14;
  const gap = size * 0.05;
  const key = (size - margin * 2 - gap * (cols - 1)) / cols;
  const top = (size - (rows * key + (rows - 1) * gap)) / 2;
  ctx.fillStyle = '#3a3d44';
  for (let r = 0; r < rows; r++) {
    for (let col = 0; col < cols; col++) {
      roundRect(ctx, margin + col * (key + gap), top + r * (key + gap), key, key, key * 0.18);
      ctx.fill();
    }
  }
  // One lit key so the icon reads as "a deck", not a blank grid.
  ctx.fillStyle = '#4c8dff';
  roundRect(ctx, margin + (key + gap), top, key, key, key * 0.18);
  ctx.fill();
  return c.toBuffer('image/png');
}

// Palette reduction, filter search and zopfli deflate; the decoded pixels do not change.
function optimize(png) {
  // eslint-disable-next-line sonarjs/no-os-command-from-path -- optional dev tool, runs by hand on a dev machine
  const run = spawnSync('oxipng', ['-o', 'max', '--zopfli', '--strip', 'safe', '--stdout', '-'], {
    input: png,
    maxBuffer: 1 << 24,
  });
  if (run.error || run.status !== 0) return png;
  return run.stdout;
}

mkdirSync(assetDir, { recursive: true });
const b64 = (size) => optimize(makeIcon(size)).toString('base64');
writeFileSync(
  join(assetDir, 'deck-icons.ts'),
  `// AUTO-GENERATED by scripts/gen-deck-icons.mjs — DO NOT EDIT\n` +
    `export const DECK_ICON_180_PNG_BASE64 =\n  '${b64(180)}';\n` +
    `export const DECK_ICON_512_PNG_BASE64 =\n  '${b64(512)}';\n`,
);
console.log('wrote src/assets/deck-icons.ts');
