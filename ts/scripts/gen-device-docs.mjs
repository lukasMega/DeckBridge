#!/usr/bin/env node
// Generates the device comparison docs from ts/src/devices/registry.ts.
//
//   node scripts/gen-device-docs.mjs            write the three artifacts
//   node scripts/gen-device-docs.mjs --check    fail if they are stale
//
// Why it lives in ts/scripts/ and not the repo-root scripts/: it imports esbuild, and
// ESM resolves bare specifiers from the IMPORTING FILE's path, not from cwd. Root
// scripts/ has no node_modules, so `import 'esbuild'` there dies with
// ERR_MODULE_NOT_FOUND no matter what the mise task's `dir` is. Same reason
// gen-splash.mjs lives here.
//
// The registry is bundled to ESM and imported: the models are pure data (registry
// reaches only driver.ts types, types.ts consts and capabilities.ts consts), so nothing
// FFI or native is pulled in. If that ever stops being true the import throws on
// `tjs:ffi` under node — a loud failure is the point.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import * as esbuild from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const TS_DIR = resolve(HERE, '..');
const REPO = resolve(TS_DIR, '..');

const REGISTRY = join(TS_DIR, 'src/devices/registry.ts');
const NOTES = join(TS_DIR, 'src/devices/device-notes.json');
const OUT_JSON = join(REPO, 'docs-site/src/data/devices.generated.json');
const OUT_DEVICES = join(REPO, 'docs/devices.mdx');
const OUT_SPECS = join(REPO, 'docs/device-specs.mdx');

const GENERATOR = 'ts/scripts/gen-device-docs.mjs';
// MDX rejects HTML comments outright ('Unexpected character `!`'), so the banner has
// to be a JSX expression comment.
const BANNER = `{/* GENERATED by ${GENERATOR} — do not edit. Run 'mise run docs-devices'. */}`;
const DASH = '—';

// ---------------------------------------------------------------- load the registry

async function loadModels() {
  const tmp = join(tmpdir(), `deckbridge-registry-${process.pid}.mjs`);
  try {
    await esbuild.build({
      entryPoints: [REGISTRY],
      bundle: true,
      format: 'esm',
      platform: 'neutral',
      outfile: tmp,
      logLevel: 'silent',
    });
    // .mjs matters: `await import()` of a .js outside a type:module package parses as CJS.
    const mod = await import(`file://${tmp}`);
    return mod.DEVICE_MODELS;
  } finally {
    rmSync(tmp, { force: true });
  }
}

/** Cross-validate: every model has notes, every note has a model. */
function loadNotes(models) {
  const { notes } = JSON.parse(readFileSync(NOTES, 'utf8'));
  const ids = new Set(models.map((m) => m.id));
  const missing = models.filter((m) => !notes[m.id]).map((m) => m.id);
  const orphan = Object.keys(notes).filter((id) => !ids.has(id));
  if (missing.length || orphan.length) {
    const parts = [];
    if (missing.length) parts.push(`models with no device-notes.json entry: ${missing.join(', ')}`);
    if (orphan.length) parts.push(`device-notes.json entries with no model: ${orphan.join(', ')}`);
    throw new Error(`${parts.join('\n')}\n(add the entry in ${NOTES}, then re-run)`);
  }
  return notes;
}

