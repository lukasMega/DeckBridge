// ---------------------------------------------------------------------- cell values

const hex = (n, pad = 4) => `0x${n.toString(16).padStart(pad, '0')}`;
function yn(v) {
  if (v === undefined) return DASH;
  return v ? 'yes' : 'no';
}
const num = (v) => (v === undefined ? DASH : String(v));

function identityCells(m) {
  return {
    name: m.name,
    id: m.id,
    vendor: m.vendor,
    protocol: m.protocol,
    driverKind: m.driverKind,
    vid: hex(m.usbVendorId),
    pids: m.usbProductIds.map((p) => hex(p)).join(' '),
    usagePage: m.usagePage === undefined ? DASH : hex(m.usagePage),
    usage: num(m.usage),
    keyCount: num(m.keyCount),
    columns: num(m.columns),
    rows: num(m.rows),
    keyWidth: num(m.keyWidth),
    keyHeight: num(m.keyHeight),
  };
}

function imageCells(m) {
  const i = m.image;
  return {
    name: m.name,
    format: i.format,
    width: num(i.width),
    height: num(i.height),
    rotate: `${i.rotate}°`,
    flipH: yn(i.flipH),
    flipV: yn(i.flipV),
    colorMode: i.colorMode,
    crop: num(i.crop),
    resizeMode: i.resizeMode ?? DASH,
    padFill: i.padFill ?? DASH,
    resizeFilter: i.resizeFilter ?? DASH,
    sharpen: num(i.sharpen),
    blur: num(i.blur),
    maxBytes: i.maxBytes === 0 ? 'no cap' : num(i.maxBytes),
    quality: i.quality === 0 ? DASH : num(i.quality),
    bmpPpm: num(i.bmpPpm),
    transform: i.transform,
  };
}

function wireCells(m) {
  const w = m.wire;
  if (!w) {
    return Object.fromEntries(
      COLUMNS.wire.map((c) => [c.key, c.key === 'name' ? m.name : DASH]),
    );
  }
  return {
    name: m.name,
    packetSize: num(w.packetSize),
    inSize: num(w.inSize),
    heartbeatMs: num(w.heartbeatMs),
    synthesizeKeyUp: yn(w.synthesizeKeyUp),
    sendStpAfterImage: yn(w.sendStpAfterImage),
    reportId: w.reportId === undefined ? DASH : hex(w.reportId, 2),
    chunkPadByte: yn(w.chunkPadByte),
    chunkDelayMs: num(w.chunkDelayMs),
    sharedSerial: yn(w.sharedSerial),
    packetSizeCandidates: w.packetSizeCandidates ? w.packetSizeCandidates.join(' / ') : DASH,
  };
}

/** "✓ tested (macOS, 2026-09-11)" / "— untested". */
function testedLabel(note) {
  const t = note.tested;
  if (!t?.status) return `${DASH} untested`;
  const meta = [t.platform, t.date].filter(Boolean).join(', ');
  return meta ? `✓ tested (${meta})` : '✓ tested';
}

// ------------------------------------------------------------------------ MDX escaping

/**
 * Escape `{` and `<` so MDX does not read them as an expression or a tag — but only
 * OUTSIDE inline code spans, where markdown already wins and a backslash would render
 * literally.
 */
function escapeMdx(text) {
  return String(text)
    .split(/(`+[^`]*`+)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/[{<]/g, (c) => `\\${c}`)))
    .join('');
}

/** Same, plus the pipe that would otherwise split a markdown table cell. */
const escapeCell = (text) => escapeMdx(text).replace(/\|/g, '\\|');

// ---------------------------------------------------------------- markdown helpers

function mdTable(headers, rows) {
  const head = `| ${headers.join(' | ')} |`;
  const rule = `|${headers.map(() => '---').join('|')}|`;
  return [head, rule, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/** Markdown inside JSX only parses with blank lines around it (MDX v3). */
function scrollable(table) {
  return ["<div style={{overflowX: 'auto'}}>", '', table, '', '</div>'].join('\n');
}

