// ------------------------------------------------------------------------- the JSON

function dataJson(models, notes) {
  const rows = models.map((m) => {
    const note = notes[m.id];
    return {
      id: m.id,
      name: m.name,
      family: familyOf(m),
      tested: Boolean(note.tested?.status),
      testedLabel: testedLabel(note),
      cells: { identity: identityCells(m), image: imageCells(m), wire: wireCells(m) },
    };
  });

  const tables = Object.fromEntries(
    Object.entries(COLUMNS).map(([table, cols]) => [
      table,
      {
        columns: cols.map((c) => ({ ...c, defaultVisible: DEFAULT_VISIBLE[table].includes(c.key) })),
        legend: DEFAULTS_LEGEND[table],
      },
    ]),
  );

  return `${JSON.stringify(
    {
      _generated: `by ${GENERATOR} — do not edit. Run 'mise run docs-devices'.`,
      tables,
      models: rows,
      // Tested first (stable within registry order) — the homepage's chip grid order.
      homepageOrder: rows
        .toSorted((a, b) => Number(b.tested) - Number(a.tested))
        .map(({ name, tested }) => ({ name, tested })),
    },
    null,
    2,
  )}\n`;
}

// ------------------------------------------------------------------------------ run

async function main() {
  const check = process.argv.includes('--check');
  const models = await loadModels();
  const notes = loadNotes(models);

  const artifacts = [
    [OUT_JSON, dataJson(models, notes)],
    [OUT_DEVICES, devicesPage(models, notes)],
    [OUT_SPECS, specsPage(models, notes)],
  ];

  if (check) {
    const stale = artifacts.filter(([file, want]) => {
      let have = null;
      try {
        have = readFileSync(file, 'utf8');
      } catch {
        return true;
      }
      return have !== want;
    });
    if (stale.length) {
      for (const [file] of stale) console.error(`stale: ${file.slice(REPO.length + 1)}`);
      console.error("\nThe device docs no longer match DEVICE_MODELS. Run 'mise run docs-devices'.");
      process.exitCode = 1;
      return;
    }
    console.log(`device docs up to date (${models.length} models)`);
    return;
  }

  for (const [file, content] of artifacts) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${file.slice(REPO.length + 1)}`);
  }
  console.log(`${models.length} models`);
}

