function familyOf(model) {
  const family = FAMILY_OF_PROTOCOL[model.protocol];
  if (!family) {
    throw new Error(
      `unmapped protocol '${model.protocol}' on model '${model.id}' — add it to FAMILY_OF_PROTOCOL in ${GENERATOR}`,
    );
  }
  return family;
}

