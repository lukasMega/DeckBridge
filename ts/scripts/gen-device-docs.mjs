/** ASCII map of mk2 key index → device wire image id, so a wrong map is visible. */
function gridDiagram(m) {
  const map = (i) =>
    m.keyMap.coraToWireImage?.[i] ?? (m.keyMap.imageOffset != null ? i + m.keyMap.imageOffset : i);
  const width = Math.max(
    ...Array.from({ length: m.keyCount }, (_, i) => String(map(i)).length),
    String(m.keyCount - 1).length,
  );
  const lines = [`mk2 index → wire image id  (${m.columns}×${m.rows}, row-major)`, ''];
  for (let r = 0; r < m.rows; r++) {
    const idx = [];
    const wire = [];
    for (let c = 0; c < m.columns; c++) {
      const i = r * m.columns + c;
      if (i >= m.keyCount) continue;
      idx.push(String(i).padStart(width));
      wire.push(String(map(i)).padStart(width));
    }
    lines.push(`  ${idx.join('  ')}      ${wire.join('  ')}`);
  }
  if (m.keyMap.extraKeys?.length) {
    lines.push('', `  extra keys (outside the CORA grid): ${m.keyMap.extraKeys.join(', ')}`);
  }
  return lines.join('\n');
}

function specSections(models, notes) {
  const out = [];
  for (const m of models) {
    const note = notes[m.id];
    out.push(`### ${escapeMdx(m.name)} \\{#${m.id}}`);
    out.push('');
    out.push(
      `\`${m.id}\` · \`${m.protocol}\` · ${escapeMdx(testedLabel(note))} · [compare entry](./devices.mdx#${m.id})`,
    );
    out.push('');
    out.push('```text');
    out.push(gridDiagram(m));
    out.push('```');
    out.push('');
    out.push('```js');
    out.push(`keyMap: ${JSON.stringify(m.keyMap, null, 2)}`);
    // productId is the PID we advertise to the Elgato app — decimal is unreadable here.
    const cora = JSON.stringify({ ...m.cora, productId: hex(m.cora.productId) }, null, 2).replace(
      /"productId": "(0x[0-9a-f]+)"/,
      '"productId": $1',
    );
    out.push(`cora: ${cora}`);
    out.push(`splash: ${JSON.stringify(m.splash ?? null, null, 2)}`);
    out.push('```');
    out.push('');
    if (note.sources?.length) {
      out.push(`**Derived from:** ${note.sources.map((s) => escapeMdx(s)).join(' · ')}`);
      out.push('');
    }
  }
  return out;
}

